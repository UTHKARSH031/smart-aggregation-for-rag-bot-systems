"""
Evaluation Metrics for RAG Systems
===================================

Measures:
1. Retrieval quality (NDCG, MAP, Recall)
2. Answer quality (ROUGE, BLEU, Exact Match)
"""

import numpy as np
from typing import List, Dict
from collections import defaultdict

class RAGEvaluator:
    """Comprehensive evaluation for RAG systems"""
    
    def __init__(self):
        self.results = []
    
    def evaluate_retrieval(
        self,
        retrieved_chunks: List,
        ground_truth_doc_ids: List[str],
        k_values: List[int] = None
    ) -> Dict[str, float]:
        """
        Evaluate retrieval quality
        
        Args:
            retrieved_chunks: List of chunks returned by system
            ground_truth_doc_ids: List of relevant document/chunk IDs
            k_values: Evaluate at different K values (default: [5, 10])
            
        Returns:
            Dictionary of metrics
        """
        if k_values is None:
            k_values = [5, 10]
        metrics = {}
        
        retrieved_ids = [
            c.chunk.doc_id if hasattr(c, 'chunk') else (
                c.doc_id if hasattr(c, 'doc_id') else c['doc_id']
            )
            for c in retrieved_chunks
        ]
        
        for k in k_values:
                         
            retrieved_k = retrieved_ids[:k]
            relevant_retrieved = len([rid for rid in retrieved_k if rid in ground_truth_doc_ids])
            precision = relevant_retrieved / k if k > 0 else 0
            metrics[f'precision@{k}'] = precision
            
            recall = relevant_retrieved / len(ground_truth_doc_ids) if ground_truth_doc_ids else 0
            metrics[f'recall@{k}'] = recall
            
            if precision + recall > 0:
                f1 = 2 * (precision * recall) / (precision + recall)
            else:
                f1 = 0
            metrics[f'f1@{k}'] = f1
        
        for k in k_values:
            ndcg = self._calculate_ndcg(retrieved_ids[:k], ground_truth_doc_ids)
            metrics[f'ndcg@{k}'] = ndcg
        
        map_score = self._calculate_map(retrieved_ids, ground_truth_doc_ids)
        metrics['map'] = map_score
        
        return metrics
    
    def evaluate_answer(
        self,
        generated_answer: str,
        ground_truth_answer: str
    ) -> Dict[str, float]:
        """
        Evaluate answer quality
        
        Args:
            generated_answer: Answer generated by LLM
            ground_truth_answer: Correct answer
            
        Returns:
            Dictionary with answer quality metrics
        """
        metrics = {}
        
        metrics['exact_match'] = 1.0 if self._normalize(generated_answer) == self._normalize(ground_truth_answer) else 0.0
        
        metrics['token_f1'] = self._calculate_token_f1(generated_answer, ground_truth_answer)
        
        metrics['rouge_l'] = self._calculate_rouge_l(generated_answer, ground_truth_answer)
        
        return metrics
    
    def _calculate_ndcg(self, retrieved: List[str], relevant: List[str]) -> float:
        """
        Calculate NDCG (Normalized Discounted Cumulative Gain)
        
        Formula:
        DCG = sum(relevance[i] / log2(i + 2)) for i in range(k)
        NDCG = DCG / IDCG (ideal DCG)
        
        Rewards:
        - Relevant documents at top positions
        """
        if not retrieved or not relevant:
            return 0.0
        
        relevances = [1.0 if doc_id in relevant else 0.0 for doc_id in retrieved]
        
        dcg = sum(rel / np.log2(i + 2) for i, rel in enumerate(relevances))
        
        ideal_relevances = sorted(relevances, reverse=True)
        idcg = sum(rel / np.log2(i + 2) for i, rel in enumerate(ideal_relevances))
        
        ndcg = dcg / idcg if idcg > 0 else 0.0
        return ndcg
    
    def _calculate_map(self, retrieved: List[str], relevant: List[str]) -> float:
        """
        Calculate MAP (Mean Average Precision)
        
        Measures: Precision at each relevant document position
        """
        if not relevant:
            return 0.0
        
        precisions = []
        relevant_count = 0
        
        for i, doc_id in enumerate(retrieved):
            if doc_id in relevant:
                relevant_count += 1
                precision_at_i = relevant_count / (i + 1)
                precisions.append(precision_at_i)
        
        if not precisions:
            return 0.0
        
        return sum(precisions) / len(relevant)
    
    def _normalize(self, text: str) -> str:
        """Normalize text for comparison"""
        return ' '.join(text.lower().split())
    
    def _calculate_token_f1(self, pred: str, truth: str) -> float:
        """
        Token-level F1 score
        
        Measures word overlap between predicted and ground truth
        """
        pred_tokens = set(self._normalize(pred).split())
        truth_tokens = set(self._normalize(truth).split())
        
        if not pred_tokens or not truth_tokens:
            return 0.0
        
        common = pred_tokens & truth_tokens
        
        if not common:
            return 0.0
        
        precision = len(common) / len(pred_tokens)
        recall = len(common) / len(truth_tokens)
        
        f1 = 2 * (precision * recall) / (precision + recall)
        return f1
    
    def _calculate_rouge_l(self, pred: str, truth: str) -> float:
        """
        ROUGE-L score (Longest Common Subsequence)
        
        Simplified implementation
        """
        pred_tokens = self._normalize(pred).split()
        truth_tokens = self._normalize(truth).split()
        
        lcs_length = self._lcs_length(pred_tokens, truth_tokens)
        
        if lcs_length == 0:
            return 0.0
        
        precision = lcs_length / len(pred_tokens) if pred_tokens else 0
        recall = lcs_length / len(truth_tokens) if truth_tokens else 0
        
        if precision + recall == 0:
            return 0.0
        
        f1 = 2 * (precision * recall) / (precision + recall)
        return f1
    
    def _lcs_length(self, seq1: List[str], seq2: List[str]) -> int:
        """Calculate length of longest common subsequence"""
        m, n = len(seq1), len(seq2)
        
        dp = [[0] * (n + 1) for _ in range(m + 1)]
        
        for i in range(1, m + 1):
            for j in range(1, n + 1):
                if seq1[i-1] == seq2[j-1]:
                    dp[i][j] = dp[i-1][j-1] + 1
                else:
                    dp[i][j] = max(dp[i-1][j], dp[i][j-1])
        
        return dp[m][n]
    
    def print_metrics(self, metrics: Dict[str, float], title: str = "Metrics"):
        """Pretty print metrics"""
        print(f"\n{'='*60}")
        print(f"{title}")
        print(f"{'='*60}")
        for key, value in metrics.items():
            print(f"{key:20s}: {value:.4f}")
        print(f"{'='*60}\n")
